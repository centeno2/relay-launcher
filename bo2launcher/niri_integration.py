"""Optional reversible Niri rule to visually hide BO2's Wine debug console.

    The console is left running: closing it can also close the game. Error and
    updater pop-ups do NOT match the exact versioned-console title pattern.
"""
from __future__ import annotations
from datetime import datetime
from pathlib import Path
import os
import shutil
import subprocess

INCLUDE = 'include "bo2-console.kdl"'
RULE = '''// Generated by BO2 Launcher. Technical console stays alive, only hidden.
window-rule {
    match title=r#"^Plutonium r[0-9]+$"#
    open-floating true
    open-focused false
    default-column-width { fixed 1; }
    default-window-height { fixed 1; }
    opacity 0.0
}
'''

def config_dir():
    return Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "niri"

def is_enabled():
    f = config_dir() / "config.kdl"
    return f.is_file() and INCLUDE in f.read_text(encoding="utf-8")

def set_enabled(enabled: bool):
    """Never overwrite existing config; write backup, validate, revert on error."""
    directory = config_dir()
    main = directory / "config.kdl"
    target = directory / "bo2-console.kdl"
    if not main.is_file():
        raise RuntimeError("No existe config.kdl de Niri; configuración manual necesaria")
    if main.is_symlink() or target.is_symlink():
        raise RuntimeError("Configuración enlazada; no se modificará automáticamente")
    original = main.read_text(encoding="utf-8")
    if enabled and is_enabled():
        return False
    if not enabled and INCLUDE not in original:
        return False
    backup = main.with_name("config.kdl.bo2-backup-" + datetime.now().strftime("%Y%m%d-%H%M%S"))
    index = 1
    while backup.exists():
        backup = main.with_name(backup.name + f"-{index}")
        index += 1
    shutil.copy2(main, backup)
    previous_rule = target.read_bytes() if target.exists() else None
    try:
        if enabled:
            target.write_text(RULE, encoding="utf-8")
            changed = original.rstrip() + "\n\n" + INCLUDE + "\n"
        else:
            changed = "\n".join(line for line in original.splitlines() if line.strip() != INCLUDE).rstrip() + "\n"
        main.write_text(changed, encoding="utf-8")
        binary = shutil.which("niri")
        if binary:
            check = subprocess.run([binary, "validate"], capture_output=True, text=True, timeout=10)
            if check.returncode != 0:
                raise RuntimeError("Niri rechazó la configuración: " + (check.stderr or check.stdout)[-700:])
        return True
    except Exception:
        main.write_text(original, encoding="utf-8")
        if previous_rule is None:
            target.unlink(missing_ok=True)
        else:
            target.write_bytes(previous_rule)
        raise
